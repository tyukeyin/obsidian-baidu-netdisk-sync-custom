// src/sync/changeScheduler.ts
var ChangeScheduler = class {
  constructor(enabled, busy, run, delay) {
    this.enabled = enabled;
    this.busy = busy;
    this.run = run;
    this.delay = delay;
    this.dirty = false;
    this.disposed = false;
  }
  changed() {
    if (this.disposed || !this.enabled()) return;
    this.dirty = true;
    this.idle();
  }
  idle() {
    if (this.disposed || !this.dirty || !this.enabled() || this.busy()) return;
    if (this.timer !== void 0) clearTimeout(this.timer);
    this.timer = setTimeout(() => {
      void this.flush();
    }, this.delay());
  }
  async flush() {
    this.timer = void 0;
    if (this.disposed || !this.enabled() || this.busy()) return;
    this.dirty = false;
    try {
      const result = await this.run();
      if (!result.success) this.dirty = true;
    } catch {
      this.dirty = true;
    }
  }
  dispose() {
    this.disposed = true;
    if (this.timer !== void 0) clearTimeout(this.timer);
  }
};

